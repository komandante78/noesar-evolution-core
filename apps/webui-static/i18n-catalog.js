// Translation catalogues.
//
// # Why the key is the English sentence and not a symbol
//
// Owner requirement, s333 point 3: «tutto in inglese principale con traduzione multilingua».
// English is therefore the SOURCE, not a translation of something else, and this file encodes
// that literally: `en` has no entries because there is nothing to look up — the markup already
// says it. A symbolic key (`home.title`) would have been the textbook choice, but it would have
// meant retrofitting eight hundred `data-i18n` attributes onto a 113 KB document whose English
// is already correct, and every one of those attributes is a place the key and the sentence can
// drift apart without anyone noticing. Here they cannot drift: the key IS the sentence.
//
// The cost of this choice, stated rather than discovered later: one English sentence gets one
// translation everywhere it appears. If a word ever needs two different renderings in two
// contexts, this shape cannot express it and something must change. No such case exists today
// (checked: no catalogue value is also a catalogue key, so nothing translates twice either).
//
// # The rule that keeps it honest
//
// A missing entry is invisible at runtime — the string renders in English and says nothing.
// That silence is exactly what the Owner saw as «un mix». So coverage is not maintained by
// discipline, it is measured: `tools/measure-ui-language-coverage.mjs` fails when a visible
// string in the markup has no entry here, and the browser check `I18N-RUNTIME` fails when
// something that only appears at render time has none. Adding a string to the interface
// without adding it here turns a check red; it does not quietly ship half-translated.
//
// # Entries whose value equals their key
//
// Some strings are the same in every language: a keyboard key (`Esc`), a log level (`WARN`), a
// protocol constant (`AGPL-3.0-or-later`), a language's own name. They are written out anyway,
// grouped under `— deliberately unchanged —`, because an entry that says "we looked at this and
// it stays" is a decision, while an ABSENT entry says nothing at all and is indistinguishable
// from an oversight. That distinction is the entire point of this file.

